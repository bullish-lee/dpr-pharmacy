#   python3 make_fixtures.py <out_dir>
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = None
for path, idx in [("/System/Library/Fonts/AppleSDGothicNeo.ttc", 0), ("/System/Library/Fonts/Supplemental/AppleGothic.ttf", 0)]:
    try:
        FONT = ImageFont.truetype(path, 12, index=idx)
        break
    except OSError:
        pass
assert FONT, "한글 글꼴 없음"

W, ROW = 700, 20
# (왼쪽, 오른쪽, 정렬)
COLS = [(0, 78, "c"), (78, 118, "c"), (118, 252, "l"), (252, 302, "r"), (302, 358, "r"), (358, 420, "r"), (420, 486, "r"), (486, 540, "c"), (540, 620, "c"), (620, 700, "c")]

def draw(rows, highlight, path):
    img = Image.new("RGB", (W, ROW * len(rows) + 1), "white")
    d = ImageDraw.Draw(img)
    for i, row in enumerate(rows):
        y = i * ROW
        if i == highlight:
            d.rectangle([0, y, W, y + ROW], fill=(255, 255, 160))
        d.line([0, y + ROW, W, y + ROW], fill=(208, 208, 208))
        for (x0, x1, al), cell in zip(COLS, row):
            if not cell:
                continue
            w = d.textlength(cell, font=FONT)
            x = {"l": x0 + 5, "r": x1 - 6 - w, "c": (x0 + x1 - w) / 2}[al]
            d.text((x, y + 3), cell, font=FONT, fill=(200, 0, 0) if cell.startswith("-") else (0, 0, 0))
    for x0, _, _ in COLS[1:]:
        d.line([x0, 0, x0, img.height], fill=(208, 208, 208))
    img.save(path, optimize=True)

